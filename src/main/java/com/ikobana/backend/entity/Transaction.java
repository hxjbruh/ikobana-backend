package com.ikobana.backend.entity;

import jakarta.persistence.*;
import jakarta.validation.constraints.*;
import lombok.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.validator.constraints.Length;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * JPA Entity representing a sales transaction in the Ikobana Frozen Food system.
 * Maps to the "transactions" table in the database.
 *
 * <p>Transaction ID format: #TRX-001, #TRX-002, etc.
 * Generated at service layer before persist.
 *
 * <p>Payment Method  : QRIS | TRANSFER_BANK | GOPAY | SHOPEE_PAY
 * <p>Payment Status  : PENDING | COMPLETED | FAILED | REFUNDED
 * <p>Delivery Status : PENDING | PROCESSING | SHIPPED | DELIVERED | CANCELLED
 */
@Entity
@Table(
    name = "transactions",
    uniqueConstraints = {
        @UniqueConstraint(name = "uk_transactions_transaction_id", columnNames = "transaction_id")
    }
)
@Data
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@ToString(exclude = {"items"})
public class Transaction {

    // ── Primary Key ──────────────────────────────────────────────────────────

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private Long id;

    // ── Transaction Identifier ───────────────────────────────────────────────

    /**
     * Human-readable transaction code, e.g. #TRX-001.
     * Generated by the service layer before persist.
     */
    @NotBlank(message = "Transaction ID is required")
    @Length(max = 50, message = "Transaction ID must not exceed 50 characters")
    @Column(name = "transaction_id", unique = true, nullable = false, length = 50)
    private String transactionId;

    // ── User Reference ────────────────────────────────────────────────────────

    /**
     * ID of the staff/admin who processed this transaction.
     */
    @NotNull(message = "User ID is required")
    @Positive(message = "User ID must be a positive number")
    @Column(nullable = false)
    private Long userId;

    // ── Customer Info ─────────────────────────────────────────────────────────

    @NotBlank(message = "Customer name is required")
    @Length(max = 100, message = "Customer name must not exceed 100 characters")
    @Column(nullable = false, length = 100)
    private String customerName;

    @NotBlank(message = "Customer phone is required")
    @Length(max = 20, message = "Customer phone must not exceed 20 characters")
    @Column(nullable = false, length = 20)
    private String customerPhone;

    @Email(message = "Customer email must be a valid email address")
    @Length(max = 100, message = "Customer email must not exceed 100 characters")
    @Column(length = 100)
    private String customerEmail;

    // ── Line Items ────────────────────────────────────────────────────────────

    /**
     * List of items in this transaction.
     * CascadeType.ALL: items are persisted/removed together with the transaction.
     * orphanRemoval: items removed from the list are deleted from the database.
     */
    @OneToMany(
        mappedBy = "transaction",
        cascade = CascadeType.ALL,
        orphanRemoval = true,
        fetch = FetchType.LAZY
    )
    private List<TransactionItem> items = new ArrayList<>();

    // ── Financials ────────────────────────────────────────────────────────────

    @NotNull(message = "Total amount is required")
    @DecimalMin(value = "0", message = "Total amount cannot be negative")
    @Column(nullable = false, precision = 19, scale = 2)
    private BigDecimal totalAmount;

    // ── Payment ───────────────────────────────────────────────────────────────

    /**
     * Payment method: QRIS | TRANSFER_BANK | GOPAY | SHOPEE_PAY
     */
    @NotBlank(message = "Payment method is required")
    @Length(max = 50, message = "Payment method must not exceed 50 characters")
    @Column(nullable = false, length = 50)
    private String paymentMethod;

    /**
     * Payment status: PENDING | COMPLETED | FAILED | REFUNDED
     */
    @NotBlank(message = "Payment status is required")
    @Length(max = 50, message = "Payment status must not exceed 50 characters")
    @Column(nullable = false, length = 50)
    private String paymentStatus = "PENDING";

    // ── Delivery ──────────────────────────────────────────────────────────────

    /**
     * Delivery status: PENDING | PROCESSING | SHIPPED | DELIVERED | CANCELLED
     */
    @NotBlank(message = "Delivery status is required")
    @Length(max = 50, message = "Delivery status must not exceed 50 characters")
    @Column(nullable = false, length = 50)
    private String deliveryStatus = "PENDING";

    // ── Notes ─────────────────────────────────────────────────────────────────

    @Length(max = 500, message = "Notes must not exceed 500 characters")
    @Column(length = 500)
    private String notes;

    // ── Audit Timestamps ─────────────────────────────────────────────────────

    @CreationTimestamp
    @Column(nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(nullable = false)
    private LocalDateTime updatedAt;

    // ── Convenience Methods ───────────────────────────────────────────────────

    /**
     * Adds a TransactionItem and sets its back-reference to this transaction.
     *
     * @param item the item to add
     */
    public void addItem(TransactionItem item) {
        items.add(item);
        item.setTransaction(this);
    }

    /**
     * Removes a TransactionItem and clears its back-reference.
     *
     * @param item the item to remove
     */
    public void removeItem(TransactionItem item) {
        items.remove(item);
        item.setTransaction(null);
    }

    // ── Business Logic Methods ────────────────────────────────────────────────

    /**
     * Calculates totalAmount as the sum of all TransactionItem subtotals.
     *
     * @return total sum as BigDecimal
     */
    public BigDecimal calculateTotalAmount() {
        return items.stream()
                .map(TransactionItem::getSubtotal)
                .filter(subtotal -> subtotal != null)
                .reduce(BigDecimal.ZERO, BigDecimal::add);
    }

    /**
     * Returns true if payment has been completed.
     *
     * @return true if paymentStatus equals "COMPLETED"
     */
    public boolean isPaid() {
        return "COMPLETED".equals(this.paymentStatus);
    }

    /**
     * Returns true if the order has been delivered.
     *
     * @return true if deliveryStatus equals "DELIVERED"
     */
    public boolean isDelivered() {
        return "DELIVERED".equals(this.deliveryStatus);
    }
}
